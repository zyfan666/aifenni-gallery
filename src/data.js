export function allocation(cents) {
  if (!Number.isSafeInteger(cents) || cents < 0)
    throw new Error("演示金额必须是非负整数分");
  const a = Math.floor((cents * 50) / 100),
    b = Math.floor((cents * 30) / 100);
  return [
    { label: "画者稿酬", percent: 50, cents: a },
    { label: "课程基金", percent: 30, cents: b },
    { label: "制作与物流", percent: 20, cents: cents - a - b },
  ];
}
