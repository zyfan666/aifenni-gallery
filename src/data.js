export function validateDraft(draft) {
  const e = {};
  if ([...draft.nickname.trim()].length > 12)
    e.nickname = "昵称请不超过 12 个字符；也可以留空。";
  if (!draft.confirmed) e.confirmed = "请确认已了解演示性质。";
  return e;
}
export function makeMemory(
  workId,
  spec,
  nickname,
  now = new Date(),
  suffix = globalThis.crypto.randomUUID().slice(0, 8).toUpperCase(),
) {
  if (!getWork(workId) || !specs[spec]) throw new Error("作品或规格不存在");
  const date = new Intl.DateTimeFormat("en-CA", {
    timeZone: "Asia/Shanghai",
    year: "numeric",
    month: "2-digit",
    day: "2-digit",
  }).format(now);
  return {
    workId,
    spec,
    nickname: nickname.trim() || "爱画的朋友",
    priceCents: specs[spec].priceCents,
    date,
    dateText: new Intl.DateTimeFormat("zh-CN", {
      timeZone: "Asia/Shanghai",
      dateStyle: "long",
    }).format(now),
    id: `DEMO-${date.replaceAll("-", "")}-${suffix}`,
  };
}
export function rememberDraft(drafts, workId, patch) {
  return {
    ...drafts,
    [workId]: {
      nickname: "",
      confirmed: false,
      spec: "print",
      ...drafts[workId],
      ...patch,
    },
  };
}
